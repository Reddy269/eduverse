class OnboardInstructorInteractor:
    def __init__(self,
                 storage: InstructorStorageInterface,
                 gateway: InstructorProfileInterface,
                 ):
        self.storage = storage
        self.gateway = gateway

    # gets detais from accounts and return in the DTO form
    def get_profile(self,request:str):
        # request refers to the unique instructor id generated by accounts
        # rules for RequestInstructorProfileDTO
        profile_details = self.gateway.get_profile(request)
        return profile_details


    # tkes in the DTO and saves ; before it takes the DTO ; the view has to add the other relevant details
    def save_profile(self,request:RequestOnboardInstructorDTO):
        # rules for onboarding:
        # 1: check if

        self.storage.save_profile(request)

